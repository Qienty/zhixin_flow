/* Run against an isolated TETHER_DATA_DIR server. Requires Playwright and Edge. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const base = process.env.TETHER_TEST_URL || 'http://127.0.0.1:8766';
const output = path.resolve('.cache/ui-preview');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.EDGE_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, serviceWorkers: 'block', reducedMotion: 'reduce' });
    const page = await context.newPage();
    page.setDefaultTimeout(12000);
    page.on('dialog', dialog => dialog.accept());
    const errors = [], writes = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', req => { if (['POST', 'PATCH', 'DELETE'].includes(req.method())) writes.push({ url: req.url(), data: req.postData() }); });
    const action = name => page.locator(`[data-act="e-${name}"]`);
    const closed = () => page.locator('#overlay').waitFor({ state: 'hidden' });
    const confirm = yes => page.locator(`button[data-act="confirm-${yes ? 'ok' : 'cancel'}"]`).click();
    const entries = async () => (await (await context.request.get(base + '/api/entries')).json()).items;
    const assertFit = async () => { assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'horizontal overflow'); };
    await fs.mkdir(output, { recursive: true });
    await page.goto(base);
    await page.locator('.expression-card').waitFor();
    await page.screenshot({ path: path.join(output, 'expression-guest-mobile.png'), fullPage: true });
    await page.locator('#expression-home-text').fill('考试结束后有点失落，但还没想清楚。');
    await action('open').click();
    assert.equal(await page.locator('[data-expression-field="need"]').count(), 0);
    await page.locator('[data-act="e-mode"][data-mode="clarify"]').click();
    await page.locator('[data-expression-field="need"]').fill('先让我把话说完。');
    await page.locator('[data-act="e-mode"][data-mode="space"]').click();
    await page.locator('[data-act="e-mode"][data-mode="clarify"]').click();
    assert.equal(await page.locator('[data-expression-field="need"]').inputValue(), '先让我把话说完。');
    await page.goBack(); await closed();
    assert.equal(await page.locator('#expression-home-text').inputValue(), '考试结束后有点失落，但还没想清楚。');
    await action('open').click();
    await page.locator('.expression-save summary').click();
    const downloading = page.waitForEvent('download');
    await action('download').click();
    const downloaded = await downloading;
    const downloadedPath = path.join(output, 'expression-test-download.txt');
    await downloaded.saveAs(downloadedPath);
    assert((await fs.readFile(downloadedPath, 'utf8')).includes('先让我把话说完。'));
    assert.equal(writes.length, 0);
    assert(!(await page.evaluate(() => JSON.stringify({ ...localStorage }) + JSON.stringify({ ...sessionStorage }))).includes('考试结束'));
    await action('clear').click(); await confirm(false);
    assert.equal(await page.locator('#expression-dialog-text').inputValue(), '考试结束后有点失落，但还没想清楚。');
    await action('clear').click(); await confirm(true); await closed();
    assert.equal(await page.locator('#expression-home-text').inputValue(), '');
    console.log('PASS Guest expression, mode switching, back, download and clearing send no writes');

    const username = 'expression_' + Date.now();
    await page.locator('#expression-home-text').fill('登录前还想保留的文字');
    await page.locator('[data-act="auth-mode"][data-mode="register"]').click();
    await page.locator('[name="username"]').fill(username);
    await page.locator('[name="password"]').fill('Expression.test.2026!');
    await page.locator('.auth-submit').click(); await confirm(false);
    assert.equal(await page.locator('#expression-home-text').inputValue(), '登录前还想保留的文字');
    assert.equal(writes.length, 0);
    await page.locator('.auth-submit').click(); await confirm(true);
    await page.locator('.home-layout').waitFor();
    assert.equal(await page.locator('#expression-home-text').inputValue(), '');
    assert.equal((await entries()).length, 0);
    console.log('PASS Authentication warns about unsaved writing and never uploads the guest draft');
    const text = '面试后还没收到结果 <img src=x onerror=alert(1)>';
    await page.locator('#expression-home-text').fill(text);
    await action('open').click();
    await page.locator('[data-act="e-mode"][data-mode="clarify"]').click();
    await page.locator('[data-expression-field="facts"]').fill('昨天完成面试，约定一周内答复。');
    await page.locator('[data-expression-field="need"]').fill('想知道接下来可以做什么。');
    await page.locator('.expression-save summary').click();
    await action('save').click();
    assert.equal((await entries()).length, 0);
    await page.locator('#expression-emotion').selectOption('anxiety');
    await action('save').click(); await confirm(false);
    assert.equal((await entries()).length, 0);
    await page.locator('#toast.show').waitFor({ state: 'hidden' });
    await page.locator('.expression-sheet').evaluate(node => { node.scrollTop = 0; });
    await page.screenshot({ path: path.join(output, 'expression-reflection-mobile.png') });
    await action('save').click(); await confirm(true); await closed();
    const saved = (await entries())[0];
    assert.equal(saved.cause, text);
    assert(saved.note.includes('昨天完成面试'));
    assert.equal(saved.intervention_completed, false);
    assert.equal(await page.locator('#expression-home-text').inputValue(), '');
    await page.locator('.tab[data-view="log"]').click();
    await page.locator(`[data-act="edit-entry"][data-id="${saved.id}"]`).click();
    assert((await page.locator('[data-input="note"]').inputValue()).includes('昨天完成面试'));
    assert.equal(await page.locator('#overlay img').count(), 0);
    await page.locator('[data-input="note"]').fill('修改后的补充说明');
    await page.locator('[data-act="save-note"]').click(); await closed();
    assert.equal((await entries())[0].note, '修改后的补充说明');
    console.log('PASS Explicit account save, validation, cancellation, escaping and editable reflection notes');

    await page.locator('.tab[data-view="now"]').click();
    await page.locator('#expression-home-text').fill('网络出错也不要丢掉这段话。');
    await action('open').click(); await page.locator('.expression-save summary').click();
    await page.locator('#expression-emotion').selectOption('sadness');
    const attempts = []; let lose = true;
    await page.route('**/api/entries?*', async route => {
      if (route.request().method() === 'POST') {
        attempts.push(route.request().postDataJSON());
        if (lose) { lose = false; const result = await route.fetch(); assert(result.ok()); return route.abort('failed'); }
      }
      return route.continue();
    });
    await action('save').click(); await confirm(true);
    await page.locator('.expression-error').waitFor();
    assert.equal((await entries()).length, 2);
    assert.equal(await page.locator('#expression-dialog-text').isEditable(), false);
    await action('save').click(); await closed();
    assert.equal((await entries()).length, 2);
    assert.deepEqual(attempts[0], attempts[1]);
    await page.unroute('**/api/entries?*');
    console.log('PASS A lost save response preserves the draft and retries without duplicate records');

    await page.locator('[data-act="pick"][data-emotion="anxiety"]').click();
    await page.locator('[data-act="guide-start"]').waitFor();
    assert.equal(await page.locator('[data-act="iv-next"]').count(), 0);
    await page.locator('[data-act="record-direct"]').click();
    await page.locator('[data-input="cause"]').fill('先记下来，不做引导。');
    await page.locator('[data-act="save-note"]').click(); await closed();
    assert.equal((await entries()).length, 3);
    await page.locator('[data-act="pick"][data-emotion="anger"]').click();
    await page.locator('[data-act="guide-start"]').click();
    await page.locator('[data-act="iv-next"]').waitFor();
    await page.keyboard.press('Escape'); await closed();
    assert.equal((await entries()).length, 3);
    console.log('PASS Emotion selection offers record or guide, with no automatic entry creation');

    await assertFit();
    await page.screenshot({ path: path.join(output, 'expression-home-mobile.png'), fullPage: true });
    await page.setViewportSize({ width: 320, height: 760 }); await assertFit();
    await page.evaluate(() => { localStorage.setItem('tether.lang', 'en'); localStorage.setItem('tether.theme', 'dark'); });
    await page.reload(); await page.locator('.home-layout').waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    await action('open').click();
    await page.locator('[data-act="e-mode"][data-mode="next"]').click();
    await page.locator('.expression-save summary').click();
    await assertFit();
    assert(!(await page.locator('.expression-sheet').innerText()).includes('express.'));
    await page.locator('.expression-sheet').evaluate(node => { node.scrollTop = 0; });
    await page.screenshot({ path: path.join(output, 'expression-english-dark-mobile.png') });
    await page.keyboard.press('Escape'); await closed();
    await page.setViewportSize({ width: 1280, height: 900 });
    await page.evaluate(() => { localStorage.setItem('tether.lang', 'zh'); localStorage.setItem('tether.theme', 'light'); });
    await page.reload(); await page.locator('.home-layout').waitFor();
    await assertFit();
    await page.screenshot({ path: path.join(output, 'expression-home-desktop.png'), fullPage: true });
    assert.deepEqual(errors, []);
    assert(!writes.some(write => write.url.includes('/insights/analyze')));
    console.log('PASS 320px, 390px and desktop layouts, English/dark theme, no browser errors or AI calls');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
