export function setLang(lang) {
  current = lang === "en" ? "en" : "zh";
  document.documentElement.lang = current === "zh" ? "zh-CN" : "en";
  document.title = DOC_TITLE[current];
  const desc = document.querySelector('meta[name="description"]');
  if (desc) desc.setAttribute("content", DOC_DESC[current]);
}

export function getLang() {
  return current;
}

export function t(key, vars) {
  const table = dict[current] || dict.zh;
  let text = table[key] ?? dict.zh[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function applyStaticText(root = document) {
  root.querySelectorAll("[data-i18n-aria]").forEach((node) => { node.setAttribute("aria-label", t(node.dataset.i18nAria)); node.title = t(node.dataset.i18nAria); });
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
}
